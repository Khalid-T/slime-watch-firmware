# THE BUILD ID (doctor's first word): the git hash baked into the
# firmware at build time. A PlatformIO pre-script (platformio.ini:
# `extra_scripts = pre:tools/build_id.py`, inherited by `ota` through
# `extends`; the watch-ancs env is gone since 09-10 21:50).
#
# Why a generated header and not a -D on the build line: a CPPDEFINES
# change is global, so every commit would recompile every source; a
# header only doctor.cpp includes recompiles doctor.cpp alone. The file
# is src/build_id.h, gitignored, rewritten only when its content changes
# (SCons sees the mtime, so an unchanged hash costs nothing).
#
# The id: `git rev-parse --short=7 HEAD`, with a `+` when tracked files
# are modified (the worktree is dirty: the number you see may not be the
# commit's), `nogit` when git is not there. Also stamped: the env name
# and the build's date.
import os
import subprocess
import time

Import("env")  # noqa: F821 (SCons)


def git(*args):
    try:
        return subprocess.check_output(
            ["git", *args], cwd=env.subst("$PROJECT_DIR"),
            stderr=subprocess.DEVNULL, text=True).strip()
    except Exception:
        return ""


build_id = git("rev-parse", "--short=7", "HEAD") or "nogit"
if build_id != "nogit" and git("status", "--porcelain", "--untracked-files=no"):
    build_id += "+"

path = os.path.join(env.subst("$PROJECT_DIR"), "src", "build_id.h")
text = (
    "/* generated by tools/build_id.py at build time -- not in git */\n"
    "#pragma once\n"
    '#define BUILD_ID   "%s"\n'
    '#define BUILD_ENV  "%s"\n'
    '#define BUILD_DATE "%s"\n'
) % (build_id, env.subst("$PIOENV"), time.strftime("%Y-%m-%d %H:%M"))

# the date line changes every minute: compare without it, so a rebuild
# in the same commit does not recompile doctor.cpp for nothing
old = ""
if os.path.exists(path):
    with open(path) as f:
        old = f.read()


def sans_date(s):
    return "\n".join(l for l in s.splitlines() if "BUILD_DATE" not in l)


if sans_date(old) != sans_date(text):
    with open(path, "w") as f:
        f.write(text)
    print("build_id: %s (%s)" % (build_id, env.subst("$PIOENV")))
